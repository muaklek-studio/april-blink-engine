//! The game's scripts as editor assets: create one from the Assets panel, open it in a code
//! editor, drag it onto a node.
//!
//! Scripts are Rust, written with the `ab-script` SDK: each lives in
//! `<game>/src/scripts/<name>.rs` and holds one or more `Script` types. The editor keeps
//! `src/scripts/mod.rs` in step with the folder (a module per file, every
//! `impl Script for T` registered as `"T"`), and the game's `register`
//! calls `scripts::register`, so a new script needs no hand-written registration. Saving a
//! script rebuilds the game's library and hot reload brings it into Play mode.

use anyhow::{bail, Context as _, Result};
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{Duration, Instant, SystemTime};

/// First line of the generated `mod.rs`; a file without it belongs to the user and is left
/// alone.
const GENERATED: &str = "// @generated by the April Blink editor from the files in this folder.";

/// The Rust keywords and names a script type cannot take.
const RESERVED: &[&str] = &[
    "Self",
    "Script",
    "Scripts",
    "Tree",
    "Node",
    "Signal",
    "Registry",
    "Color",
    "Transform",
    "Box",
    "Option",
    "Result",
    "String",
    "Vec",
    "Some",
    "None",
    "Ok",
    "Err",
];

/// Drag-and-drop payload: a script type name, from the Assets panel onto a node.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ScriptDrag(pub String);

/// A script file and the script types it defines.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ScriptFile {
    pub path: PathBuf,
    /// Module name (the file stem).
    pub module: String,
    /// Each `impl Script for T`: the type name and its 1-based line.
    pub types: Vec<(String, usize)>,
    modified: Option<SystemTime>,
}

impl ScriptFile {
    /// The script a drag or a double-click means: the file's first type, else its module.
    pub fn main_type(&self) -> Option<&str> {
        self.types.first().map(|(t, _)| t.as_str())
    }

    pub fn file_name(&self) -> String {
        format!("{}.rs", self.module)
    }
}

/// The game crate behind a project's asset folder: `<game>/assets` → `<game>`, or Night
/// Relics' crate for the engine's own `assets`.
pub fn game_crate(assets: &Path) -> Option<PathBuf> {
    let assets = assets
        .canonicalize()
        .unwrap_or_else(|_| assets.to_path_buf());
    let parent = assets.parent()?;
    if parent.join("Cargo.toml").is_file() && parent.join("src/lib.rs").is_file() {
        return Some(parent.to_path_buf());
    }
    // The engine's own assets: Night Relics.
    if parent.join("crates/ab-slice/src/lib.rs").is_file() {
        return Some(parent.join("crates/ab-slice"));
    }
    None
}

/// `"enemy ai"`, `"enemy_ai"`, `"EnemyAI"` → `"EnemyAi"`… keeping capitals the user typed
/// inside words (`"EnemyAI"` stays). Errors explain what is wrong with the name.
pub fn type_name(input: &str) -> Result<String, String> {
    let mut name = String::new();
    for word in input
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
    {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            name.push(first.to_ascii_uppercase());
            name.extend(chars);
        }
    }
    if name.is_empty() {
        return Err("Type a name, like Enemy or DoorSwitch.".into());
    }
    if !input
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == ' ' || c == '_' || c == '-')
    {
        return Err("Use Latin letters and digits only.".into());
    }
    if name.starts_with(|c: char| c.is_ascii_digit()) {
        return Err("A script name cannot start with a digit.".into());
    }
    if RESERVED.contains(&name.as_str()) {
        return Err(format!("`{name}` is a name the engine already uses."));
    }
    Ok(name)
}

/// `"EnemyAI"` → `"enemy_ai"`, `"Door2Switch"` → `"door2_switch"`.
pub fn module_name(type_name: &str) -> String {
    let chars: Vec<char> = type_name.chars().collect();
    let mut out = String::new();
    for (i, &c) in chars.iter().enumerate() {
        if c.is_ascii_uppercase() {
            let prev = i.checked_sub(1).map(|p| chars[p]);
            let next = chars.get(i + 1);
            let boundary = prev.is_some_and(|p| p.is_ascii_lowercase() || p.is_ascii_digit())
                || (prev.is_some_and(|p| p.is_ascii_uppercase())
                    && next.is_some_and(|n| n.is_ascii_lowercase()));
            if boundary {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    // Module names that are Rust keywords.
    match out.as_str() {
        "type" | "move" | "loop" | "match" | "mod" | "ref" | "use" | "fn" | "impl" | "trait"
        | "struct" | "enum" | "static" | "const" | "crate" | "super" | "self" | "dyn" | "async"
        | "await" | "box" | "where" | "for" | "while" | "if" | "else" | "in" | "let" | "mut"
        | "pub" | "return" | "true" | "false" | "unsafe" | "extern" | "break" | "continue"
        | "as" | "yield" | "try" | "macro" | "gen" => {
            format!("{out}_script")
        }
        _ => out,
    }
}

/// The source of a new script.
pub fn template(type_name: &str) -> String {
    format!(
        r#"//! {type_name}: attach it to a node by dragging this script onto the node in the editor.

use ab_script::prelude::*;

/// What this script remembers between frames goes in here, e.g. `speed: f32,`. Fields are
/// kept when the scripts are rebuilt while the game runs (`serde_state!` below).
#[derive(Debug, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct {type_name} {{}}

impl Script for {type_name} {{
    serde_state!();

    /// Once, when the node and its children are in the scene.
    fn ready(&mut self, tree: &mut Tree<'_>, node: Node) {{
        let _ = (tree, node);
    }}

    /// Every frame; `delta` is the time since the last one, in seconds.
    fn process(&mut self, tree: &mut Tree<'_>, node: Node, delta: f32) {{
        let _ = (tree, node, delta);
    }}

    // Also available: physics_process (fixed steps, for movement), on_signal, exit_tree.
}}
"#
    )
}

/// The script types `source` defines: `impl Script for T` (also with a path, like
/// `ab_script::Script`), outside comments; generic impls are skipped.
pub fn script_types(source: &str) -> Vec<(String, usize)> {
    let mut types = Vec::new();
    let mut in_block_comment = false;
    for (index, line) in source.lines().enumerate() {
        let mut line = line.trim();
        if in_block_comment {
            match line.find("*/") {
                Some(end) => {
                    in_block_comment = false;
                    line = line[end + 2..].trim();
                }
                None => continue,
            }
        }
        if line.starts_with("/*") && !line.contains("*/") {
            in_block_comment = true;
            continue;
        }
        if line.starts_with("//") {
            continue;
        }
        let Some(rest) = line.strip_prefix("impl ") else {
            continue;
        };
        let Some((trait_path, target)) = rest.split_once(" for ") else {
            continue;
        };
        if trait_path.trim().rsplit("::").next() != Some("Script") {
            continue;
        }
        let name: String = target
            .trim()
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
            .collect();
        let generic = target.trim()[name.len()..].starts_with('<');
        if !name.is_empty() && !generic && !types.iter().any(|(t, _)| *t == name) {
            types.push((name, index + 1));
        }
    }
    types
}

/// Text of the generated `mod.rs` for these files.
pub fn module_file(files: &[ScriptFile]) -> String {
    let mut out = format!(
        "{GENERATED}\n\
         //! Scripts made in the editor (Assets → Create → Script). This file is rewritten when\n\
         //! scripts are added or removed: write code in the script files, not here.\n"
    );
    let mut registered: Vec<(&str, &str)> = Vec::new();
    for file in files {
        out.push_str(&format!("\npub mod {};", file.module));
        for (name, _) in &file.types {
            // Two files defining the same name: the first wins (the editor warns).
            if !registered.iter().any(|(_, n)| n == name) {
                registered.push((&file.module, name));
            }
        }
    }
    if !files.is_empty() {
        out.push('\n');
    }
    out.push_str("\n/// Registers every script in this folder under its type name.\n");
    if registered.is_empty() {
        out.push_str("pub fn register(_registry: &mut ab_script::Registry) {}\n");
    } else {
        out.push_str("pub fn register(registry: &mut ab_script::Registry) {\n");
        for (module, name) in registered {
            let line = format!("    registry.register::<{module}::{name}>({name:?});");
            // As rustfmt writes it: past 100 columns the call goes on its own line.
            if line.chars().count() > 100 {
                out.push_str(&format!(
                    "    registry\n        .register::<{module}::{name}>({name:?});\n"
                ));
            } else {
                out.push_str(&line);
                out.push('\n');
            }
        }
        out.push_str("}\n");
    }
    out
}

/// `lib.rs` with `pub mod scripts;` and a `scripts::register(..)` call in its `register`
/// function, or `None` when it has them already. Errors when `register` cannot be found.
pub fn wire_lib(text: &str) -> Result<Option<String>, String> {
    let has_mod = text
        .lines()
        .any(|l| matches!(l.trim(), "mod scripts;" | "pub mod scripts;"));
    let has_call = text.contains("scripts::register(");
    if has_mod && has_call {
        return Ok(None);
    }
    let mut text = text.to_owned();
    if !has_call {
        let start = text
            .find("pub fn register(")
            .ok_or("no `pub fn register(registry: &mut Registry)` in src/lib.rs")?;
        let params_start = start + "pub fn register(".len();
        let params_end = params_start
            + text[params_start..]
                .find(')')
                .ok_or("cannot read `register`'s parameters")?;
        let param = text[params_start..params_end]
            .split(':')
            .next()
            .map(str::trim)
            .filter(|p| !p.is_empty())
            .ok_or("cannot read `register`'s parameter name")?
            .to_owned();
        let brace = params_end
            + text[params_end..]
                .find('{')
                .ok_or("cannot find the body of `register`")?;
        let empty_body = text[brace..].starts_with("{}");
        let used = param.trim_start_matches('_').to_owned();
        if empty_body {
            // `register(_registry: …) {}` → uses the registry now.
            text.replace_range(
                brace..brace + 2,
                &format!("{{\n    scripts::register({used});\n}}"),
            );
            if used != param {
                text.replace_range(params_start..params_start + param.len(), &used);
            }
        } else {
            text.insert_str(brace + 1, &format!("\n    scripts::register({param});"));
        }
    }
    if !has_mod {
        // Before the first `use`, else after the crate docs.
        let at = text
            .match_indices('\n')
            .map(|(i, _)| i + 1)
            .chain(std::iter::once(0))
            .filter(|&i| text[i..].starts_with("use "))
            .min()
            .unwrap_or_else(|| {
                let mut at = 0;
                for line in text.split_inclusive('\n') {
                    if line.starts_with("//!") || line.trim().is_empty() && at > 0 {
                        at += line.len();
                    } else {
                        break;
                    }
                }
                at
            });
        text.insert_str(at, "pub mod scripts;\n\n");
    }
    Ok(Some(text))
}

/// The scripts folder of one game, rescanned now and then.
#[derive(Debug)]
pub struct GameScripts {
    /// The game crate (`Cargo.toml`, `src/`).
    pub crate_root: PathBuf,
    pub files: Vec<ScriptFile>,
    /// Scripts written by hand elsewhere in `src/` (`lib.rs`, …): found, opened, never
    /// changed.
    pub other: Vec<ScriptFile>,
    scanned: Option<Instant>,
    /// Problems to show (a hand-written `mod.rs`, a `register` that cannot be wired, …).
    pub warning: Option<String>,
}

impl GameScripts {
    pub fn new(crate_root: PathBuf) -> Self {
        let mut scripts = Self {
            crate_root,
            files: Vec::new(),
            other: Vec::new(),
            scanned: None,
            warning: None,
        };
        scripts.rescan();
        scripts
    }

    pub fn dir(&self) -> PathBuf {
        self.crate_root.join("src/scripts")
    }

    /// Rescans when the last scan is older than a second (the folder is small).
    pub fn refresh(&mut self) {
        if self
            .scanned
            .is_none_or(|t| t.elapsed() > Duration::from_secs(1))
        {
            self.rescan();
        }
    }

    /// Reads the folder; when the set of scripts changed (also by hand, outside the editor),
    /// rewrites `mod.rs`.
    pub fn rescan(&mut self) {
        self.scanned = Some(Instant::now());
        self.other = self.scan_other();
        let mut files = Vec::new();
        for entry in std::fs::read_dir(self.dir())
            .into_iter()
            .flatten()
            .flatten()
        {
            let path = entry.path();
            let Some(stem) = path
                .file_stem()
                .and_then(|s| s.to_str())
                .filter(|_| path.extension().is_some_and(|e| e == "rs"))
            else {
                continue;
            };
            let valid_module = stem != "mod"
                && stem.starts_with(|c: char| c.is_ascii_lowercase() || c == '_')
                && stem
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
            if !valid_module {
                continue;
            }
            let modified = entry.metadata().ok().and_then(|m| m.modified().ok());
            // Unchanged files keep their parse.
            let known = self
                .files
                .iter()
                .find(|f| f.path == path && f.modified == modified && modified.is_some());
            let types = match known {
                Some(file) => file.types.clone(),
                None => script_types(&std::fs::read_to_string(&path).unwrap_or_default()),
            };
            files.push(ScriptFile {
                module: stem.to_owned(),
                path,
                types,
                modified,
            });
        }
        files.sort_by(|a, b| a.module.cmp(&b.module));
        let changed = files.len() != self.files.len()
            || files
                .iter()
                .zip(&self.files)
                .any(|(a, b)| a.module != b.module || a.types != b.types);
        self.files = files;
        if changed && self.dir().is_dir() {
            if let Err(err) = self.sync() {
                self.warning = Some(format!("{err:#}"));
            }
        }
    }

    /// Script types in `src/*.rs` (outside the scripts folder).
    fn scan_other(&self) -> Vec<ScriptFile> {
        let mut out = Vec::new();
        let src = self.crate_root.join("src");
        for entry in std::fs::read_dir(&src).into_iter().flatten().flatten() {
            let path = entry.path();
            if path.extension().is_none_or(|e| e != "rs") {
                continue;
            }
            let modified = entry.metadata().ok().and_then(|m| m.modified().ok());
            let known = self
                .other
                .iter()
                .find(|f| f.path == path && f.modified == modified && modified.is_some());
            let types = match known {
                Some(file) => file.types.clone(),
                None => script_types(&std::fs::read_to_string(&path).unwrap_or_default()),
            };
            if !types.is_empty() {
                out.push(ScriptFile {
                    module: path
                        .file_stem()
                        .map(|s| s.to_string_lossy().into_owned())
                        .unwrap_or_default(),
                    path,
                    types,
                    modified,
                });
            }
        }
        out.sort_by(|a, b| a.module.cmp(&b.module));
        out
    }

    /// Brings `mod.rs` and `lib.rs` up to date with the files.
    pub fn sync(&mut self) -> Result<()> {
        let dir = self.dir();
        std::fs::create_dir_all(&dir)?;
        let module = dir.join("mod.rs");
        let current = std::fs::read_to_string(&module).ok();
        if current
            .as_deref()
            .is_some_and(|text| !text.starts_with(GENERATED))
        {
            bail!(
                "{} was written by hand: the editor does not change it. Register new scripts \
                 there yourself.",
                module.display()
            );
        }
        let wanted = module_file(&self.files);
        if current.as_deref() != Some(wanted.as_str()) {
            std::fs::write(&module, wanted)
                .with_context(|| format!("writing {}", module.display()))?;
        }
        let lib = self.crate_root.join("src/lib.rs");
        let text =
            std::fs::read_to_string(&lib).with_context(|| format!("reading {}", lib.display()))?;
        match wire_lib(&text) {
            Ok(Some(wired)) => {
                std::fs::write(&lib, wired).with_context(|| format!("writing {}", lib.display()))?
            }
            Ok(None) => {}
            Err(reason) => bail!(
                "{reason}: add `pub mod scripts;` and call `scripts::register(registry)` in \
                 your register function"
            ),
        }
        let duplicates: Vec<&str> = self
            .all_types()
            .enumerate()
            .filter(|(i, (name, _))| self.all_types().take(*i).any(|(n, _)| n == *name))
            .map(|(_, (name, _))| name)
            .collect();
        self.warning = (!duplicates.is_empty()).then(|| {
            format!(
                "Two scripts define {}: only the first is used.",
                duplicates.join(", ")
            )
        });
        Ok(())
    }

    /// Every script type with its file.
    pub fn all_types(&self) -> impl Iterator<Item = (&str, &ScriptFile)> {
        self.files
            .iter()
            .flat_map(|f| f.types.iter().map(move |(t, _)| (t.as_str(), f)))
    }

    /// The file and line defining script `name` (in the scripts folder, else elsewhere in
    /// `src/`).
    pub fn find(&self, name: &str) -> Option<(&ScriptFile, usize)> {
        self.files.iter().chain(&self.other).find_map(|f| {
            f.types
                .iter()
                .find(|(t, _)| t == name)
                .map(|(_, line)| (f, *line))
        })
    }

    /// Creates `src/scripts/<module>.rs` for a script named from `input`; `taken` are script
    /// names in use elsewhere (the game's own `register`). Returns the type name and file.
    #[cfg(test)]
    pub fn create(&mut self, input: &str, taken: &[String]) -> Result<(String, PathBuf)> {
        self.create_from(input, taken, None)
    }

    /// [`GameScripts::create`] starting from a template's code (its type renamed).
    pub fn create_from(
        &mut self,
        input: &str,
        taken: &[String],
        template: Option<&ab_project::script_templates::ScriptTemplate>,
    ) -> Result<(String, PathBuf)> {
        let name = type_name(input).map_err(anyhow::Error::msg)?;
        let defined = self.find(&name).is_some();
        if taken.contains(&name) || defined {
            bail!("A script named {name} already exists.");
        }
        let dir = self.dir();
        std::fs::create_dir_all(&dir)?;
        let path = dir.join(format!("{}.rs", module_name(&name)));
        if path.exists() {
            bail!("{} already exists.", path.display());
        }
        let source = match template {
            Some(t) => t.source_for(&name),
            None => self::template(&name),
        };
        std::fs::write(&path, source).with_context(|| format!("writing {}", path.display()))?;
        self.rescan();
        self.sync()?;
        Ok((name, path))
    }

    /// Deletes a script file (and unregisters it).
    pub fn delete(&mut self, path: &Path) -> Result<()> {
        if path.parent() != Some(self.dir().as_path()) {
            bail!("{} is not a script of this game", path.display());
        }
        std::fs::remove_file(path).with_context(|| format!("deleting {}", path.display()))?;
        self.rescan();
        self.sync()
    }
}

