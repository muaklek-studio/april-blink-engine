/// A code editor found on this machine.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodeEditor {
    pub name: &'static str,
    program: PathBuf,
    kind: EditorKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum EditorKind {
    /// `code <folder> -g <file>:<line>` (VS Code, VSCodium, Cursor).
    VsCode,
    /// `<program> <folder> <file>:<line>` (Zed, Sublime Text).
    FolderAndFile,
    /// `<program> <file>` (anything set with `AB_CODE_EDITOR`).
    FileOnly,
}

/// `name` in the `PATH` (with `.exe` / `.cmd` on Windows).
fn which(name: &str) -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    let suffixes: &[&str] = if cfg!(windows) {
        &[".exe", ".cmd", ".bat"]
    } else {
        &[""]
    };
    std::env::split_paths(&path).find_map(|dir| {
        suffixes
            .iter()
            .map(|s| dir.join(format!("{name}{s}")))
            .find(|p| p.is_file())
    })
}

/// The code editor to open scripts with: `AB_CODE_EDITOR` if set, else the first of VS Code,
/// VSCodium, Cursor, Zed or Sublime Text installed. `None`: the system's default app.
pub fn code_editor() -> Option<CodeEditor> {
    if let Some(program) = std::env::var_os("AB_CODE_EDITOR").filter(|p| !p.is_empty()) {
        let program = PathBuf::from(program);
        let stem = program
            .file_stem()
            .map(|s| s.to_string_lossy().to_lowercase())
            .unwrap_or_default();
        let kind = if matches!(stem.as_str(), "code" | "codium" | "cursor") {
            EditorKind::VsCode
        } else {
            EditorKind::FileOnly
        };
        return Some(CodeEditor {
            name: "AB_CODE_EDITOR",
            program: which(&program.to_string_lossy()).unwrap_or(program),
            kind,
        });
    }
    [
        ("code", "VS Code", EditorKind::VsCode),
        ("codium", "VSCodium", EditorKind::VsCode),
        ("cursor", "Cursor", EditorKind::VsCode),
        ("zed", "Zed", EditorKind::FolderAndFile),
        ("zeditor", "Zed", EditorKind::FolderAndFile),
        ("subl", "Sublime Text", EditorKind::FolderAndFile),
    ]
    .into_iter()
    .find_map(|(program, name, kind)| {
        which(program).map(|program| CodeEditor {
            name,
            program,
            kind,
        })
    })
}

/// The command that opens `file` at `line`, with the game's folder as the workspace (so
/// rust-analyzer finds the crate).
fn open_command(editor: &CodeEditor, file: &Path, line: usize, folder: &Path) -> Command {
    let target = format!("{}:{line}", file.display());
    // Windows runs `.cmd` launchers (VS Code's `code.cmd`) through cmd.
    let mut command = if cfg!(windows)
        && editor
            .program
            .extension()
            .is_some_and(|e| e.eq_ignore_ascii_case("cmd") || e.eq_ignore_ascii_case("bat"))
    {
        let mut command = ab_project::process::command("cmd");
        command.arg("/C").arg(&editor.program);
        command
    } else {
        Command::new(&editor.program)
    };
    match editor.kind {
        EditorKind::VsCode => command.arg(folder).arg("-g").arg(target),
        EditorKind::FolderAndFile => command.arg(folder).arg(target),
        EditorKind::FileOnly => command.arg(file),
    };
    command
}

/// Opens `file` at `line`; returns the editor's name ("the system's default app" when none
/// was found).
pub fn open_script(file: &Path, line: usize, folder: &Path) -> Result<String> {
    match code_editor() {
        Some(editor) => {
            open_command(&editor, file, line, folder)
                .spawn()
                .with_context(|| format!("starting {}", editor.program.display()))?;
            Ok(editor.name.to_owned())
        }
        None => {
            open_with_system(file)?;
            Ok("the system's default app".into())
        }
    }
}

/// Opens a file or folder with the system's default application.
pub fn open_with_system(path: &Path) -> Result<()> {
    let mut command = if cfg!(windows) {
        let mut c = Command::new("explorer");
        c.arg(path);
        c
    } else if cfg!(target_os = "macos") {
        let mut c = Command::new("open");
        c.arg(path);
        c
    } else {
        let mut c = Command::new("xdg-open");
        c.arg(path);
        c
    };
    command
        .spawn()
        .with_context(|| format!("opening {}", path.display()))?;
    Ok(())
}

