    #[test]
    fn creates_registers_and_deletes_scripts_in_a_game() {
        let root = std::env::temp_dir().join(format!("ab-scripts-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("src")).unwrap();
        std::fs::write(
            root.join("src/lib.rs"),
            "use ab_script::Registry;\n\npub fn register(registry: &mut Registry) {\n    registry.register::<Player>(\"Player\");\n}\n",
        )
        .unwrap();
        std::fs::write(
            root.join("src/player.rs"),
            "pub struct Player;\nimpl Script for Player {}\n",
        )
        .unwrap();
        let mut scripts = GameScripts::new(root.clone());
        assert!(scripts.files.is_empty());
        let (file, line) = scripts.find("Player").unwrap();
        assert_eq!(
            (file.module.as_str(), line),
            ("player", 2),
            "hand-written scripts too"
        );
        assert!(
            scripts.create("Player", &[]).is_err(),
            "defined in src/player.rs"
        );

        let (name, path) = scripts.create("enemy ai", &[]).unwrap();
        assert_eq!(name, "EnemyAi");
        assert_eq!(path, root.join("src/scripts/enemy_ai.rs"));
        assert_eq!(scripts.find("EnemyAi").unwrap().1, 11, "its `impl Script`");
        let module = std::fs::read_to_string(root.join("src/scripts/mod.rs")).unwrap();
        assert!(module.contains("registry.register::<enemy_ai::EnemyAi>(\"EnemyAi\");"));
        let lib = std::fs::read_to_string(root.join("src/lib.rs")).unwrap();
        assert!(lib.contains("pub mod scripts;") && lib.contains("scripts::register(registry);"));

        assert!(scripts.create("EnemyAi", &[]).is_err(), "taken");
        assert!(
            scripts.create("Player", &["Player".into()]).is_err(),
            "taken by lib.rs"
        );

        // A file added by hand is picked up on the next scan.
        std::fs::write(root.join("src/scripts/door.rs"), template("Door")).unwrap();
        scripts.rescan();
        let module = std::fs::read_to_string(root.join("src/scripts/mod.rs")).unwrap();
        assert!(module.contains("pub mod door;") && module.contains("door::Door"));

        scripts.delete(&path).unwrap();
        assert!(scripts.find("EnemyAi").is_none());
        let module = std::fs::read_to_string(root.join("src/scripts/mod.rs")).unwrap();
        assert!(!module.contains("enemy_ai"));

        // A hand-written mod.rs is not touched.
        std::fs::write(root.join("src/scripts/mod.rs"), "// mine\n").unwrap();
        assert!(scripts.sync().is_err());
        assert_eq!(
            std::fs::read_to_string(root.join("src/scripts/mod.rs")).unwrap(),
            "// mine\n"
        );
        let _ = std::fs::remove_dir_all(&root);
    }

